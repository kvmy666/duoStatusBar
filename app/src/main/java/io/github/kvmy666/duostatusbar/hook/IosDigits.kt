    /** The horizontal bearing that centres a glyph in its advance cell. */
    fun bearing(glyph: Glyph): Float = (glyph.advance - glyph.width) / 2f

    /** The digit for [ch], or `0` when a caller passes something that is not a digit. */
    fun glyph(ch: Char): Glyph = GLYPHS[ch] ?: GLYPHS.getValue('0')

    /**
     * One closed [Path] with every contour of [glyph], translated to ([originX], [originY]).
     * The fill type is [Path.FillType.EVEN_ODD], so the counters are knocked out regardless of
     * their winding direction.
     */
    fun buildPath(glyph: Glyph, originX: Float, originY: Float): Path = Path().apply {
        fillType = Path.FillType.EVEN_ODD
        for (contour in glyph.contours) {
            moveTo(originX + contour[0], originY + contour[1])
            var i = 2
            while (i < contour.size) {
                lineTo(originX + contour[i], originY + contour[i + 1])
                i += 2
            }
            close()
        }
    }

    /**
     * Ink width of [text] when every glyph is centred in its own advance cell:
     * `sum(advances) - firstBearing - lastBearing`.
     */
    fun textInkWidth(text: String): Float {
        if (text.isEmpty()) return 0f
        var total = 0f
        for (ch in text) total += glyph(ch).advance
        total -= bearing(glyph(text.first()))
        total -= bearing(glyph(text.last()))
        return total
    }

    /** [textInkWidth] plus the inline bolt when [withBolt] is set. */
    fun groupWidth(text: String, withBolt: Boolean): Float =
        textInkWidth(text) + if (withBolt) INLINE_BOLT_GAP + INLINE_BOLT_W else 0f

    /**
     * The colour the percentage is drawn in: the status-bar background, so the filled contours
     * knock out of both the charged fill and the neutral remainder. A light tint implies a dark
     * bar and vice versa.
     */
    fun backgroundColour(tint: Int): Int {
        val luminance = (Color.red(tint) * 299 + Color.green(tint) * 587 + Color.blue(tint) * 114) / 1000
        return if (luminance > 127) 0xFF000000.toInt() else 0xFFFFFFFF.toInt()
    }

    /**
     * A closed bolt from [BOLT_NORMALIZED], scaled to [w] x [h] and centred at ([cx], [cy]).
     * The normalised point box is the design box: the ink may fall just inside an edge.
     */
    fun boltPath(w: Float, h: Float, cx: Float, cy: Float): Path {
        val left = cx - w / 2f
        val top = cy - h / 2f
        return Path().apply {
            var i = 0
            while (i < BOLT_NORMALIZED.size) {
                val x = left + BOLT_NORMALIZED[i] * w
                val y = top + BOLT_NORMALIZED[i + 1] * h
                if (i == 0) moveTo(x, y) else lineTo(x, y)
                i += 2
            }
            close()
        }
    }

    /** The large bolt centred on the battery body. */
    fun largeBoltPath(): Path = boltPath(
