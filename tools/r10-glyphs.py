#!/usr/bin/env python3
"""Deterministic generator for the R10A runtime glyph tables.

Reads rive/ios/glyphs-r10.json and emits either:
  kotlin  app/src/main/java/io/github/kvmy666/duostatusbar/hook/R10Glyphs.kt
  rml     rive/ios/generated-r10-digits.rml (the battery digit artboard section)

Usage (from the repository root):
  python3 tools/r10-glyphs.py kotlin          # write Kotlin to stdout
  python3 tools/r10-glyphs.py rml             # write RML to stdout
  python3 tools/r10-glyphs.py kotlin --check  # regenerate to /tmp and byte-diff
  python3 tools/r10-glyphs.py rml --check     # the committed files
  python3 tools/r10-glyphs.py kotlin > app/src/main/java/io/github/kvmy666/duostatusbar/hook/R10Glyphs.kt
  python3 tools/r10-glyphs.py rml    > rive/ios/generated-r10-digits.rml

This is the repo-pathed copy of .pm/out-r10/trace/gen_r10_glyphs.py.  The generated
header keeps the provenance path of the original measurement generator; the data
itself is the committed rive/ios/glyphs-r10.json.  `--check` writes under
/tmp/r10a-d/gen-check and never writes into the repository.

Rive encoding used by `rml` (exact attribute names from the installed 1.9.1
docs, ~/.rive/versions/1.9.1/docs/drawing.md, and the shipped `text_rain`
sample):
  <CubicDetachedVertex x="..." y="..." inRotation="..." inDistance="..."
                       outRotation="..." outDistance="..."/>
  <PointsPath isClosed="true" isClockwise="true|false" name="...">
  <Fill fillRule="evenOdd" name="Fill">
Rotations are radians pointing FROM the vertex TO that handle; distances are
units (hypot).  inRotation == outRotation + pi at a smooth vertex.  An anchor is
each cubic segment's start point; the closing segment's second control point is
folded onto the first vertex as its in-handle.  The local CLI (1.9.1) refuses
command dispatch because CI pins 1.9.2 ("rive 1.9.2 is required (you have
1.9.1)"), so `rive schema` could not be run here; no file under ~/.rive was
modified.
"""

from __future__ import annotations

import hashlib
import json
import math
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_JSON = ROOT / "rive/ios/glyphs-r10.json"
GENERATED = {
    "kotlin": ROOT / "app/src/main/java/io/github/kvmy666/duostatusbar/hook/R10Glyphs.kt",
    "rml": ROOT / "rive/ios/generated-r10-digits.rml",
}
CHECK_DIR = Path("/tmp/r10a-d/gen-check")
DIGIT_ORDER = "0123456789"
LABEL_ORDER = "LTEG345+"


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def num(v: float, nd: int = 5) -> str:
    if abs(v) < 0.5 * 10 ** (-nd):
        v = 0.0
    s = f"{v:.{nd}f}".rstrip("0").rstrip(".")
    return "0" if s in ("", "-0") else s


def kf(v: float) -> str:
    if abs(v) < 0.0005:
        v = 0.0
    s = f"{v:.3f}".rstrip("0").rstrip(".")
    return f"{s}f"


def seg_start(seg: list[float]) -> tuple[float, float]:
    return float(seg[0]), float(seg[1])


def seg_end(seg: list[float]) -> tuple[float, float]:
    return float(seg[6]), float(seg[7])


def signed_area(anchors: list[tuple[float, float]]) -> float:
    a = 0.0
    n = len(anchors)
    for i in range(n):
        x0, y0 = anchors[i]
        x1, y1 = anchors[(i + 1) % n]
        a += x0 * y1 - x1 * y0
    return 0.5 * a


def kotlin_text(data: dict, data_sha: str) -> str:
    L: list[str] = []
    L.append("// =============================================================================")
    L.append("// R10A measured glyph tables - GENERATED by .pm/out-r10/trace/gen_r10_glyphs.py")
    L.append(f"// Data: r10-glyphs.json sha256 {data_sha}")
    L.append("// Digits cap 60.7, labels cap 71.4 design units; y DOWN, cap top y=0, ink-left x=0.")
    L.append("// One contour = one closed cubic list [sx,sy,c1x,c1y,c2x,c2y,ex,ey, ...].")
    L.append("// Contour order is outer first, then holes; the first point is not repeated.")
    L.append("// advanceMeasured=false marks an advance extrapolated from the median side bearing.")
    L.append("// Do not hand-edit: rerun the generator (kotlin subcommand).")
    L.append("// =============================================================================")
    L.append("package io.github.kvmy666.duostatusbar.hook")
    L.append("")
    L.append("internal object R10Glyphs {")
    L.append("    const val DIGIT_CAP = 60.7f")
    L.append("    const val LABEL_CAP = 71.4f")
    L.append("")
    L.append("    /**")
    L.append("     * One measured glyph in design units. [contours] is outer first then holes;")
    L.append("     * each contour is a closed cubic segment list (8 floats per segment).")
    L.append("     */")
    L.append("    class Glyph(")
    L.append("        val char: Char,")
    L.append("        val width: Float,")
    L.append("        val advance: Float,")
    L.append("        val advanceMeasured: Boolean,")
    L.append("        val contours: Array<FloatArray>,")
    L.append("    )")
    L.append("")

    def fn_name(section_name: str, ch: str) -> str:
        if section_name == "DIGITS":
            return f"digit{ch}"
        return "label" + ("Plus" if ch == "+" else ch)

    def emit_glyph(section_name: str, section: dict, ch: str) -> None:
        g = section["glyphs"][ch]
        L.append(f"    private fun {fn_name(section_name, ch)}(): Glyph = Glyph(")
        L.append(f"        char = '{ch}',")
        L.append(f"        width = {kf(g['width'])},")
        L.append(f"        advance = {kf(g['advance'])},")
        L.append(f"        advanceMeasured = {'true' if g['advance_measured'] else 'false'},")
        L.append("        contours = arrayOf(")
        for contour in g["contours"]:
            L.append("            floatArrayOf(")
            for seg in contour:
                vals = ", ".join(kf(float(v)) for v in seg)
                L.append(f"                {vals},")
            L.append("            ),")
        L.append("        ),")
        L.append("    )")
        L.append("")

    def emit_map(name: str, section: dict, order: str) -> None:
        for ch in order:
            emit_glyph(name, section, ch)
        L.append(f"    val {name}: Map<Char, Glyph> = mapOf(")
        for ch in order:
            L.append(f"        '{ch}' to {fn_name(name, ch)}(),")
        L.append("    )")
        L.append("")

    emit_map("DIGITS", data["digits"], DIGIT_ORDER)
    emit_map("LABELS", data["labels"], LABEL_ORDER)
    L.append("}")
    return "\n".join(L) + "\n"


def rml_text(data: dict, data_sha: str) -> str:
    L: list[str] = []
    L.append("<!-- ============================================================================")
    L.append("     R10A battery digit artboard - GENERATED by .pm/out-r10/trace/gen_r10_glyphs.py")
    L.append(f"     Data: r10-glyphs.json sha256 {data_sha}")
    L.append("     Digits: cap 60.7 design units, cap top y=0, baseline y=60.7, y DOWN.")
    L.append("     One Shape per digit; outer path first, then one PointsPath per hole, and ONE")
    L.append("     Fill fillRule=\"evenOdd\" for the whole shape.  Each Node x is the cumulative")
    L.append("     measured advance (catalogue placement; move/zero it when binding at runtime).")
    L.append("")
    L.append("     Vertex attribute names (installed 1.9.1 docs + text_rain sample; the local")
    L.append("     CLI refuses dispatch because CI pins 1.9.2, so `rive schema` was not run):")
    L.append("       <CubicDetachedVertex x= y= inRotation= inDistance= outRotation= outDistance=/>")
    L.append("     rotations are radians from the vertex to that handle; distances are hypot units;")
    L.append("     anchors are the cubic segment endpoints; the closing segment's c2 is the first")
    L.append("     vertex's in-handle. isClockwise follows the y-down vertex order.")
    L.append("     ============================================================================ -->")
    L.append('<Node name="r10DigitArtboard">')

    cum = 0.0
    digits = data["digits"]["glyphs"]
    for ch in DIGIT_ORDER:
        g = digits[ch]
        x = num(cum, 4)
        flag = "measured" if g["advance_measured"] else "extrapolated"
        L.append("")
        L.append(
            f'  <!-- digit {ch}: width {num(g["width"], 3)}, advance {num(g["advance"], 3)} ({flag}), '
            f'{g["contour_count"]} contour(s), {g["hole_count"]} hole(s) -->'
        )
        L.append(f'  <Node name="digit{ch}" x="{x}" y="0">')
        L.append(f'    <Shape name="digit{ch}Ink">')
        for ci, contour in enumerate(g["contours"]):
            segs = [list(map(float, s)) for s in contour]
            n = len(segs)
            anchors = [seg_start(s) for s in segs]
            # guard the closed chain (the rounded data is expected to be exact)
            for i in range(n):
                if seg_end(segs[i]) != seg_start(segs[(i + 1) % n]):
                    raise RuntimeError(f"digit {ch} contour {ci}: open segment chain at {i}")
            cw = signed_area(anchors) > 0.0
            name = f"digit{ch}Outer" if ci == 0 else f"digit{ch}Hole{ci}"
            L.append(
                f'      <PointsPath isClosed="true" isClockwise="{"true" if cw else "false"}" name="{name}">'
            )
            for i, seg in enumerate(segs):
                vx, vy = anchors[i]
                out = (seg[2] - vx, seg[3] - vy)
                prev = segs[(i - 1) % n]
                inn = (prev[4] - vx, prev[5] - vy)
                out_d = math.hypot(out[0], out[1])
                in_d = math.hypot(inn[0], inn[1])
                out_r = math.atan2(out[1], out[0]) if out_d > 1e-12 else 0.0
                in_r = math.atan2(inn[1], inn[0]) if in_d > 1e-12 else 0.0
                L.append(
                    '        <CubicDetachedVertex x="{}" y="{}" inRotation="{}" inDistance="{}" '
                    'outRotation="{}" outDistance="{}"/>'.format(
                        num(vx), num(vy), num(in_r, 6), num(in_d, 5), num(out_r, 6), num(out_d, 5)
                    )
                )
            L.append("      </PointsPath>")
        L.append('      <Fill fillRule="evenOdd" name="Fill">')
        L.append('        <SolidColor colorValue="FFFFFFFF" name="Color"/>')
        L.append("      </Fill>")
        L.append("    </Shape>")
        L.append("  </Node>")
        cum += g["advance"]
    L.append("</Node>")
    return "\n".join(L) + "\n"


def main(argv: list[str]) -> int:
    if len(argv) < 2 or argv[1] not in ("kotlin", "rml"):
        sys.stderr.write("usage: r10-glyphs.py {kotlin|rml} [--check] [--input PATH]\n")
        return 2
    mode = argv[1]
    check = "--check" in argv[2:]
    inp = DEFAULT_JSON
    if "--input" in argv:
        inp = Path(argv[argv.index("--input") + 1])
    raw = inp.read_bytes()
    data = json.loads(raw.decode("utf-8"))
    data_sha = sha256_bytes(raw)
    if mode == "kotlin":
        text = kotlin_text(data, data_sha)
        # cheap structural guard: balanced braces, every contour float is an f-literal
        if text.count("{") != text.count("}"):
            raise RuntimeError("kotlin output: unbalanced braces")
    else:
        text = rml_text(data, data_sha)
        # well-formedness guard (the RML is XML)
        ET.fromstring("<root>" + text + "</root>")

    if not check:
        sys.stdout.write(text)
        return 0

    CHECK_DIR.mkdir(parents=True, exist_ok=True)
    name = GENERATED[mode].name
    tmp = CHECK_DIR / name
    tmp.write_bytes(text.encode("utf-8"))
    ref = GENERATED[mode]
    if not ref.exists():
        sys.stderr.write(
            f"missing reference {ref}; create it with: python3 {sys.argv[0]} {mode} > {ref}\n"
        )
        return 2
    a = tmp.read_bytes()
    b = ref.read_bytes()
    if a == b:
        print(f"OK {name}: bytes={len(a)} sha256={sha256_bytes(a)}")
        return 0
    # first differing byte/line for a useful failure
    limit = min(len(a), len(b))
    at = next((i for i in range(limit) if a[i] != b[i]), limit)
    line = a[:at].count(b"\n") + 1
    sys.stderr.write(
        f"DIFF {name}: bytes {len(a)} vs {len(b)}, first difference at byte {at} (line {line})\n"
        f"  /tmp: {a[max(0, at - 40):at + 40]!r}\n"
        f"  ref : {b[max(0, at - 40):at + 40]!r}\n"
    )
    return 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
